/** The characters a backslash escapes. */
const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);
const CONTINUED = /^ {2,}\S/;

/** A fence's language, or null when `line` does not open one. */
function fenceOpen(line) {
  if (line.length < 3 || line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let j = 3;
  const n = line.length;
  while (j < n) {
    const c = line.charCodeAt(j);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) j++;
    else break;
  }
  const lang = line.slice(3, j);
  while (j < n) {
    const c = line.charCodeAt(j);
    if (c !== 32 && c !== 9) return null;
    j++;
  }
  return lang;
}

/** True when `line` closes a fence. */
function fenceClose(line) {
  if (line.length < 3 || line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let j = 3; j < line.length; j++) {
    const c = line.charCodeAt(j);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's level and text, or null (a heading's text is never empty). */
function headingOf(line) {
  let n = 0;
  while (n < line.length && line.charCodeAt(n) === 35) n++;
  if (n === 0 || n > 6 || n >= line.length) return null;
  const c = line.charCodeAt(n);
  if (c !== 32 && c !== 9) return null;
  let a = n;
  while (a < line.length && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  let b = line.length;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  if (b <= a) return null;
  return { depth: n, text: line.slice(a, b) };
}

/** True when `line` is a thematic break. */
function isHR(line) {
  if (!line.startsWith('---') && !line.startsWith('***')) return false;
  for (let j = 3; j < line.length; j++) {
    const c = line.charCodeAt(j);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. Only those open with a blank, a backtick, a hash, a dash or a star. */
function endsParagraph(line) {
  const c = line.charCodeAt(0);
  if (c === 96) return fenceOpen(line) !== null;
  if (c === 35) return headingOf(line) !== null;
  if (c === 45 || c === 42) return isHR(line);
  if (c !== 32 && c !== 9 && c === c) return false;
  return isBlank(line);
}

/** A bullet item's content, or null. */
function bulletOf(line) {
  const c0 = line.charCodeAt(0);
  if ((c0 === 45 || c0 === 42) && line.charCodeAt(1) === 32) return line.slice(2);
  return null;
}

/** An ordered item's number and content, or null. */
function orderedOf(line) {
  let j = 0;
  while (j < line.length && j < 9) {
    const c = line.charCodeAt(j);
    if (c >= 48 && c <= 57) j++;
    else break;
  }
  if (j === 0) return null;
  if (line.charCodeAt(j) !== 46 || line.charCodeAt(j + 1) !== 32) return null;
  return { num: line.slice(0, j), content: line.slice(j + 2) };
}

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/** `s` rendered inline, appended to `out`; `env.link(target)` is a link's href. Plain runs are escaped in bulk; the scanner jumps from one special character to the next with indexOf instead of walking every character. */
function inlineTo(out, s, env) {
  let i = 0;
  let plainStart = 0;
  const n = s.length;
  while (i < n) {
    let j = n;
    let k;
    k = s.indexOf('\\', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('`', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('*', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('[', i);
    if (k !== -1 && k < j) j = k;
    if (j >= n) break;
    const c = s[j];
    if (c === '\\') {
      if (j + 1 < n && ESCAPABLE.has(s[j + 1])) {
        if (j > plainStart) out.push(escapeHtml(s.slice(plainStart, j)));
        out.push(s[j + 1]);
        i = j + 2;
        plainStart = i;
      } else {
        i = j + 1;
      }
      continue;
    }
    if (c === '`') {
      const m = s.indexOf('`', j + 1);
      if (m > j + 1) {
        if (j > plainStart) out.push(escapeHtml(s.slice(plainStart, j)));
        out.push('<code>', escapeHtml(s.slice(j + 1, m)), '</code>');
        i = m + 1;
        plainStart = i;
      } else {
        i = j + 1;
      }
      continue;
    }
    if (c === '*') {
      if (s[j + 1] === '*') {
        const m = findUnescaped(s, '**', j + 2);
        if (m > j + 2) {
          if (j > plainStart) out.push(escapeHtml(s.slice(plainStart, j)));
          out.push('<strong>');
          inlineTo(out, s.slice(j + 2, m), env);
          out.push('</strong>');
          i = m + 2;
          plainStart = i;
        } else {
          i = j + 2;
        }
        continue;
      }
      const m = findSingleStar(s, j + 1);
      if (m > j + 1) {
        if (j > plainStart) out.push(escapeHtml(s.slice(plainStart, j)));
        out.push('<em>');
        inlineTo(out, s.slice(j + 1, m), env);
        out.push('</em>');
        i = m + 1;
        plainStart = i;
      } else {
        i = j + 1;
      }
      continue;
    }
    const k2 = findUnescaped(s, ']', j + 1);
    const m = k2 !== -1 && s[k2 + 1] === '(' ? s.indexOf(')', k2 + 2) : -1;
    const target = m === -1 ? '' : s.slice(k2 + 2, m);
    if (target !== '' && !/\s/.test(target)) {
      if (j > plainStart) out.push(escapeHtml(s.slice(plainStart, j)));
      out.push('<a href="', escapeHtml(env.link(target)), '">');
      inlineTo(out, s.slice(j + 1, k2), env);
      out.push('</a>');
      i = m + 1;
      plainStart = i;
    } else {
      i = j + 1;
    }
  }
  if (n > plainStart) out.push(escapeHtml(s.slice(plainStart)));
}

/** `src` rendered in one pass: its HTML, its table of contents, its excerpt and its word count. */
function renderMarkdown(src, env, C) {
  const lines = src.split('\n');
  let words = 0;
  for (const l of lines) words += countWords(l);
  const ids = new Set();
  const parts = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const lang = fenceOpen(line);
    if (lang !== null) {
      i++;
      const body = [];
      while (i < lines.length && !fenceClose(lines[i])) body.push(lines[i++]);
      i++;
      parts.push('<pre><code', lang === '' ? '' : ` class="language-${escapeHtml(lang)}"`, '>');
      // '\n' passes the escape through, so the whole body escapes as one string.
      if (body.length !== 0) parts.push(escapeHtml(`${body.join('\n')}\n`));
      parts.push('</code></pre>\n');
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text, C.slugCache), ids);
      const tmp = [];
      inlineTo(tmp, heading.text, env);
      const html = tmp.join('');
      parts.push(`<h${heading.depth} id="${id}">`, html, `</h${heading.depth}>\n`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHR(line)) {
      parts.push('<hr>\n');
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      const qlines = [];
      while (i < lines.length && lines[i].charCodeAt(0) === 62) {
        const l = lines[i++];
        qlines.push(trimST(l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1)));
      }
      const body = qlines.filter((l) => l !== '');
      if (body.length === 0) parts.push('<blockquote>\n</blockquote>\n');
      else {
        parts.push('<blockquote>\n<p>');
        inlineTo(parts, body.join('\n'), env);
        parts.push('</p>\n</blockquote>\n');
      }
      continue;
    }
    const bContent = bulletOf(line);
    const oMatch = bContent === null ? orderedOf(line) : null;
    if (bContent !== null || oMatch !== null) {
      const isOrdered = oMatch !== null;
      const start = isOrdered ? Number(oMatch.num) : 1;
      const items = [];
      while (i < lines.length) {
        const l = lines[i];
        if (isOrdered) {
          const m = orderedOf(l);
          if (m !== null) {
            items.push(trimST(m.content));
            i++;
            continue;
          }
        } else {
          const bc = bulletOf(l);
          if (bc !== null) {
            items.push(trimST(bc));
            i++;
            continue;
          }
        }
        if (CONTINUED.test(l)) {
          items[items.length - 1] += `\n${trimST(l)}`;
          i++;
          continue;
        }
        break;
      }
      parts.push(isOrdered && start !== 1 ? `<ol start="${start}">\n` : isOrdered ? '<ol>\n' : '<ul>\n');
      for (const item of items) {
        parts.push('<li>');
        inlineTo(parts, item, env);
        parts.push('</li>\n');
      }
      parts.push(isOrdered ? '</ol>\n' : '</ul>\n');
      continue;
    }
    const body = [trimST(line)];
    i++;
    while (i < lines.length && !endsParagraph(lines[i])) body.push(trimST(lines[i++]));
    const tmp = [];
    inlineTo(tmp, body.join('\n'), env);
    const html = tmp.join('');
    if (excerpt === null) excerpt = html;
    parts.push('<p>', html, '</p>\n');
  }
  return { html: parts.join(''), toc, excerpt: excerpt ?? '', words };
}

