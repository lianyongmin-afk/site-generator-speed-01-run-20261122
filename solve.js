// solve.js — a faster drop-in for makefun-site 1.0.0.
//
// run(input) returns exactly what makefun-site 1.0.0's build() returns for
// the same input, byte for byte. The reference's rules (README.md in the kit)
// are re-implemented directly, with the slow parts replaced by equivalent
// fast paths:
//   - Markdown is lexed and rendered in a single pass (no token objects),
//     lines are classified by hand instead of by seven regexes, and inline
//     markup escapes plain runs in bulk instead of one regex call per char.
//   - slugify() is cached per run and skips NFKD for pure-ASCII text.
//   - Templates render into one shared string array, and scopes are kept as
//     a prototype chain of null-prototype objects, so a path's first name
//     resolves by a single native property lookup.
//   - A page's card is computed once and reused by its layout.
// All caches are created fresh inside run(): nothing is carried from one
// case to the next. Dependency-free ES module.

/** Code-unit order (never the locale's). */
const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** The HTML escape table, in this order: & < > " ' . */
const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

/** `text` with & < > " and ' escaped. */
function escapeHtml(text) {
  return text.replace(/[&<>"']/g, (c) => ESCAPES[c]);
}

/** A slug is at most this many characters before a collision suffix. */
const SLUG_MAX = 64;

/** The slug of `text`, uncached. ASCII text skips NFKD (identity on ASCII). */
function slugifyRaw(text) {
  const plain = /[^\x00-\x7F]/.test(text) ? text.normalize('NFKD').replace(/\p{M}/gu, '') : text;
  let out = '';
  let gap = false;
  for (let i = 0; i < plain.length; i++) {
    const code = plain.charCodeAt(i);
    let keep = null;
    if (code >= 65 && code <= 90) keep = String.fromCharCode(code + 32);
    else if ((code >= 97 && code <= 122) || (code >= 48 && code <= 57)) keep = plain[i];
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

/** The slug of `text`, cached in `cache` (one cache per run). */
function slugify(text, cache) {
  const hit = cache.get(text);
  if (hit !== undefined) return hit;
  const out = slugifyRaw(text);
  cache.set(text, out);
  return out;
}

/** `slug` made unique against `taken` (and added to it). */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** A YYYY-MM-DD date in words, cached in `cache` (one cache per run). */
function longDate(date, cache) {
  let v = cache.get(date);
  if (v === undefined) {
    v = `${Number(date.slice(8, 10))} ${MONTHS[Number(date.slice(5, 7)) - 1]} ${date.slice(0, 4)}`;
    cache.set(date, v);
  }
  return v;
}

/** The words of one line: its runs of characters other than whitespace (JS \s). */
function countWords(line) {
  let n = 0;
  let inW = false;
  for (let i = 0; i < line.length; i++) {
    const c = line.charCodeAt(i);
    let ws;
    if (c === 32 || c === 9 || c === 10 || c === 11 || c === 12 || c === 13) ws = true;
    else if (c < 160) ws = false;
    else ws = c === 160 || c === 5760 || (c >= 8192 && c <= 8202) || c === 8232 || c === 8233 || c === 8239 || c === 8287 || c === 12288 || c === 65279;
    if (ws) inW = false;
    else if (!inW) {
      inW = true;
      n++;
    }
  }
  return n;
}

